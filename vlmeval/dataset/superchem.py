def _safe_filename_from_url(url):
    return osp.basename(url.split('?', 1)[0])


def _guess_mime(url, image_bytes=None):
    if image_bytes and image_bytes.startswith(b'\xff\xd8\xff'):
        return 'jpeg'
    if image_bytes and image_bytes.startswith(b'\x89PNG'):
        return 'png'
    lower = url.lower()
    if lower.endswith(('.jpg', '.jpeg')):
        return 'jpeg'
    if lower.endswith('.png'):
        return 'png'
    return 'jpeg'


def _normalise_answer_list(answer):
    if isinstance(answer, np.ndarray):
        answer = answer.tolist()
    if isinstance(answer, str) and answer.startswith('[') and answer.endswith(']'):
        answer = toliststr(answer)
    if not isinstance(answer, (list, tuple)):
        answer = [answer]
    return [str(x).strip().upper() for x in answer if x is not None and str(x).strip()]


def _score_multiple_choice_answer(answer, ref_answers):
    answer = str(answer).strip()
    ref_answers = _normalise_answer_list(ref_answers)
    return int(len(answer) == len(ref_answers) and set(answer.upper()) == set(ref_answers))


def _score_answer(answer, ref_answers, question_type):
    ref_answers = _normalise_answer_list(ref_answers)
    if question_type == 'multiple_choice':
        return _score_multiple_choice_answer(answer, ref_answers)
    if question_type == 'fill_blank':
        if not ref_answers:
            return 0
        return int(str(answer).strip().lower() == ref_answers[0].lower())
    raise ValueError(f'Unsupported question type: {question_type}')


def _option_items_from_mapping(options):
    if isinstance(options, str):
        options = json.loads(options)
    if not isinstance(options, dict):
        return []
    items = []
    for key in sorted(options.keys()):
        value = options.get(key)
        if value is None:
            break
        items.append((key, value))
    return items


def _option_items_from_line(line):
    items = []
    for key in string.ascii_uppercase:
        if key not in line or pd.isna(line[key]):
            break
        items.append((key, line[key]))
    return items


def _format_options(items):
    return ''.join(f'{key}: {value}\n' for key, value in items)


def _nonempty_unique_values(values):
    result = []
    for value in set(values):
        if pd.isna(value):
            continue
        text = str(value)
        if text:
            result.append(text)
    return sorted(result)


def _safe_meta_value(mapping, key, default=''):
    value = mapping.get(key, default)
    if isinstance(value, np.ndarray):
        value = value.tolist()
    if isinstance(value, (list, dict)):
        return repr(value)
    if pd.isna(value):
        return default
    return value


def _extract_multimodal_urls(text):
    urls = []
    for tag_match in MULTIMODAL_TAG_PATTERN.finditer(text):
        link_match = MARKDOWN_IMAGE_PATTERN.match(tag_match.group(1))
        if link_match:
            urls.append(link_match.group(2))
    return urls


def _replace_multimodal_links_with_text(text):
    def replace_func(match):
        content = match.group(1)
        link_match = MARKDOWN_IMAGE_PATTERN.match(content)
        if link_match:
            return f'<MultiModal>{link_match.group(1)}</MultiModal>'
        return match.group(0)
    return MULTIMODAL_TAG_PATTERN.sub(replace_func, text)


def _extract_checkpoint_weights(explanation):
    if explanation is None:
        return []
    matches = CHECKPOINT_WEIGHT_PATTERN.findall(str(explanation))
    try:
        return [float(weight) for weight in matches]
    except ValueError:
        print(f"Warning: Failed to parse weights in text snippet: {explanation[:50]}...")
        return []


def _normalise_evaluation_details(details):
    if isinstance(details, list):
        return details
    if isinstance(details, np.ndarray):
        return details.tolist()
    if isinstance(details, dict):
        checkpoint_details = details.get('checkpoint_details')
        return checkpoint_details if isinstance(checkpoint_details, list) else []
    if details is None:
        return []
    if not isinstance(details, str):
        try:
            if pd.isna(details):
                return []
        except TypeError:
            pass
    if isinstance(details, str):
        text = details.strip()
        if not text or text.lower() in {'nan', 'none'}:
            return []
        for parser in (json.loads, ast.literal_eval):
            try:
                parsed = parser(text)
            except Exception:
                continue
            return _normalise_evaluation_details(parsed)
    return []


def _safe_number(value, default=0.0):
    try:
        if pd.isna(value):
            return default
    except TypeError:
        pass
    try:
        return float(value)
    except (TypeError, ValueError):
        return default


def _official_weighted_rpf(explanation, details, matched_checkpoints=0, total_checkpoints=0):
    weights = _extract_checkpoint_weights(explanation)
    details = _normalise_evaluation_details(details)
    if not weights:
        total = _safe_number(total_checkpoints)
        if total > 0:
            return _safe_number(matched_checkpoints) / total
        total = len(details)
        if total:
            matched = sum(1 for item in details if isinstance(item, dict) and item.get('is_matched') is True)
            return matched / total
        return np.nan

    if not details:
        return np.nan

    matches = [item.get('is_matched', False) if isinstance(item, dict) else False for item in details]
    if len(weights) != len(matches):
        min_len = min(len(weights), len(matches))
        weights = weights[:min_len]
        matches = matches[:min_len]

    total_weight = sum(weights)
    if total_weight == 0:
        return 0.0
    earned_weight = sum(weight for weight, matched in zip(weights, matches) if matched)
    return earned_weight / total_weight


def _mean_or_zero(values):
    values = pd.to_numeric(pd.Series(values), errors='coerce').dropna()
    return float(values.mean()) if len(values) else 0.0


def _parse_boxed_answer(response):
    matches = list(BOXED_ANSWER_PATTERN.finditer(str(response)))
    if not matches:
        raise ValueError('Could not find the answer in the required $\\boxed{...}$ format.')
    answer = matches[-1].group(1).strip()
    answer = (
        answer
        .replace('\\', '')
        .replace('{', '')
        .replace('}', '')
        .replace('text', '')
        .replace('math', '')
        .replace('bf', '')
        .replace('rm', '')
        .strip()
    )
    return answer


def _parse_judge_json(response):
    text = str(response)
    match = re.search(r'```json\s*([\s\S]*?)\s*```', text)
    if match:
        json_str = match.group(1)
    else:
        match = re.search(r'\{[\s\S]*\}', text)
        if match:
            json_str = match.group(0)
        else:
            raise ValueError('No valid JSON structure found in the response.')

    try:
        parsed = json.loads(json_str)
        if 'checkpoint_details' not in parsed:
            raise ValueError("Parsed JSON is missing the required 'checkpoint_details' key.")
        if not isinstance(parsed['checkpoint_details'], list):
            raise ValueError("'checkpoint_details' must be a list.")
        return parsed
    except json.JSONDecodeError as err:
        raise ValueError(f'Failed to decode JSON. Error: {err}')


def _infer_model_name_from_eval_file(eval_file, dataset_name):
    stem = osp.splitext(osp.basename(str(eval_file)))[0]
    dataset_names = tuple(dict.fromkeys((dataset_name,) + SUPERCHEM_DATASET_NAMES))
    for name in sorted(dataset_names, key=len, reverse=True):
        suffix = f'_{name}'
        if stem.endswith(suffix):
            return stem[:-len(suffix)]
    return stem


def _official_reasoning_effort_from_infer_model(model_name):
    name = str(model_name or '').strip().lower()
    name = name.replace('/', '-').replace('.', '_')
    hyphen_name = name.replace('_', '-')

    if re.search(r'(^|-)o3($|-)', hyphen_name):
        return 'high'
    if re.search(r'(^|-)o4-mini($|-)', hyphen_name):
        return 'high'
    if 'gemini' in name and ('2_5' in name or '2-5' in name) and 'pro' in name:
        return 'high'

    if re.search(r'(^|-)gpt-?5($|-)', hyphen_name):
        return 'high'

    return None


def _write_image_bytes(image_bytes, path):
    os.makedirs(osp.dirname(path), exist_ok=True)
    if not read_ok(path):
        with open(path, 'wb') as f:
            f.write(image_bytes)


def superchem_auxeval(model, line):
    prompt = line['judge_prompt']
    retry = getattr(model, 'retry', 5)
    raw, err_msg = '', ''
    for retry_idx in range(retry):
        try:
            raw = model.generate(prompt, temperature=1.0)
            parsed = _parse_judge_json(raw)
            details = parsed.get('checkpoint_details', [])
            total = len(details)
            matched = sum(1 for item in details if isinstance(item, dict) and item.get('is_matched') is True)
            return {
                'matched_checkpoints': matched,
                'total_checkpoints': total,
                'evaluation_details': details,
                'judge_output': raw,
                'status': True,
            }
        except Exception as err:
            err_msg = str(err)
            if retry_idx < retry - 1:
                time.sleep(5)

    return {
        'matched_checkpoints': 0,
        'total_checkpoints': 0,
        'evaluation_details': [],
        'judge_output': raw,
        'status': False,
        'error': err_msg,
    }


class SUPERChemDataset(ImageBaseDataset):
    TYPE = 'SUPERChem'
    DATASET_URL = {
        'SUPERChem': SUPERCHEM_URL,
        'SUPERChem_text': SUPERCHEM_URL,
    }
    DATASET_MD5 = {
        'SUPERChem': SUPERCHEM_MD5,
        'SUPERChem_text': SUPERCHEM_MD5,
    }
    DEFAULT_JUDGE_MODEL = 'gemini-2.5-pro'
    force_use_dataset_prompt = True

    def __init__(self, dataset='SUPERChem', skip_noimg=False, limit=None):
        super().__init__(dataset=dataset, skip_noimg=skip_noimg)
        if limit is not None:
            self.data = self.data.head(int(limit)).copy()

    def load_data(self, dataset):
        url = self.DATASET_URL[dataset]
        data_root = LMUDataRoot()
        dataset_root = osp.join(data_root, dataset)
        self.data_root = dataset_root
        self.img_root = osp.join(data_root, dataset, 'images')
        os.makedirs(dataset_root, exist_ok=True)
        parquet_path = osp.join(dataset_root, f'{dataset}.parquet')
        self.data_path = parquet_path
        if not osp.exists(parquet_path) or md5(parquet_path) != self.DATASET_MD5[dataset]:
            download_file(url, parquet_path)

        split_map_path = osp.join(dataset_root, f'{dataset}_dataset_split_map.json')
        if not osp.exists(split_map_path) or md5(split_map_path) != SUPERCHEM_SPLIT_MAP_MD5:
            download_file(SUPERCHEM_SPLIT_MAP_URL, split_map_path)
        with open(split_map_path, 'r', encoding='utf-8') as f:
            split_map = json.load(f)

        meta_path = osp.join(dataset_root, f'{dataset}_official_metadata.parquet')
        if not osp.exists(meta_path) or md5(meta_path) != SUPERCHEM_OFFICIAL_META_MD5:
            download_file(SUPERCHEM_OFFICIAL_META_URL, meta_path)
        metadata = pd.read_parquet(meta_path)
        meta_map = {str(row['uuid']): row for _, row in metadata.iterrows()}

        raw = pd.read_parquet(parquet_path)
        rows = []
        use_images = not self.is_text_version(dataset)
        image_root = self.img_root if use_images else None
        for _, item in raw.iterrows():
            uuid = str(item['uuid'])
            rows.append(
                self._convert_row(
                    item,
                    meta_map.get(uuid, {}),
                    split_map.get(uuid, {}),
                    image_root,
                    use_images=use_images,
                )
            )
        return pd.DataFrame(rows)

    @staticmethod
    def _convert_row(item, meta_info=None, split_info=None, image_root=None, use_images=True):
        if meta_info is None:
            meta_info = {}
        if split_info is None:
            split_info = {}
        question = item['question_en']
        options = item['options_en'] or {}
        option_items = _option_items_from_mapping(options)
        option_text = _format_options(option_items)
        multimodal_source = question + '\n' + option_text
        image_urls = _extract_multimodal_urls(multimodal_source) if use_images else []

        image_paths, image_mimes = [], []
        if use_images:
            image_maps = {}
            image_maps.update(item['question_images'] or {})
            image_maps.update(item['options_images'] or {})
            for image_url in image_urls:
                image_bytes = image_maps.get(image_url)
                if image_bytes is None:
                    raise FileNotFoundError(f'Image bytes missing for {image_url}')
                mime = _guess_mime(image_url, image_bytes)
                image_path = _safe_filename_from_url(image_url)
                if image_root is not None:
                    image_path = osp.join(image_root, image_path)
                    _write_image_bytes(image_bytes, image_path)
                image_paths.append(image_path)
                image_mimes.append(mime)

        answer_list = _normalise_answer_list(item['answer_en'])
        row = {
            'index': item['uuid'],
            'uuid': item['uuid'],
            'field': _safe_meta_value(meta_info, 'field', item.get('field', '')),
            'subfield': _safe_meta_value(meta_info, 'subfield', ''),
            'tags': _safe_meta_value(meta_info, 'tags', ''),
            'difficulty': _safe_meta_value(meta_info, 'difficulty', split_info.get('difficulty', '')),
            'source': _safe_meta_value(meta_info, 'source', ''),
            'official_split': split_info.get('split', ''),
            'question_type': item['question_type'],
            'question': question,
            'question_en': question,
            'answer': answer_list[0] if len(answer_list) == 1 else repr(answer_list),
            'answer_en': repr(answer_list),
            'explanation_en': item['explanation_en'],
            'image_urls': repr(image_urls),
            'image_mimes': repr(image_mimes),
            'image_path': repr(image_paths) if image_paths else repr([]),
            'canary': item.get('canary', ''),
        }
        for key, value in option_items:
            row[key] = value
        return row

    def dump_image(self, line):
        if isinstance(line, int):
            line = self.data.iloc[line]

        image_urls = toliststr(line['image_urls'])
        image_paths = toliststr(line['image_path'])
        if not image_urls:
            return []

        tgt_paths = []
        for image_path in image_paths:
            tgt_path = image_path if osp.isabs(image_path) else osp.join(self.img_root, image_path)
            if not read_ok(tgt_path):
                raise FileNotFoundError(f'Image file not found: {tgt_path}')
            tgt_paths.append(tgt_path)
        return tgt_paths

    def build_official_prompt(self, line):
        if isinstance(line, int):
            line = self.data.iloc[line]
        question = line['question_en'] if 'question_en' in line else line['question']
        return SUPERCHEM_INFER_PROMPT.format(
            question=question,
            options=_format_options(_option_items_from_line(line)),
        )

    def is_text_version(self, dataset=None):
        return (dataset or self.dataset_name) == 'SUPERChem_text'

    def build_text_prompt(self, line):
        return _replace_multimodal_links_with_text(self.build_official_prompt(line))

    def build_prompt(self, line):
        if isinstance(line, int):
            line = self.data.iloc[line]

        prompt = self.build_official_prompt(line)
        if self.is_text_version():
            return [{'type': 'text', 'value': _replace_multimodal_links_with_text(prompt)}]

        image_urls = toliststr(line['image_urls'])
        tgt_paths = self.dump_image(line) if image_urls else []
        url_to_path = dict(zip(image_urls, tgt_paths))

        msgs = []
        last_end = 0
        for tag_match in MULTIMODAL_TAG_PATTERN.finditer(prompt):
            if tag_match.start() > last_end:
                msgs.append({'type': 'text', 'value': prompt[last_end:tag_match.start()]})

            link_match = MARKDOWN_IMAGE_PATTERN.match(tag_match.group(1))
            if link_match is None:
                raise ValueError(f'No link found in multimodal tag: {tag_match.group(1)}')
            image_url = link_match.group(2)
            if image_url not in url_to_path:
                raise FileNotFoundError(f'Image file not found: {image_url}')
            msgs.append({
                'type': 'image',
                'value': url_to_path[image_url],
            })
            last_end = tag_match.end()

        if last_end < len(prompt):
            msgs.append({'type': 'text', 'value': prompt[last_end:]})
        return msgs

    def build_judge_prompt(self, line, prediction):
        if isinstance(line, int):
            line = self.data.iloc[line]
        prompt = SUPERCHEM_COT_JUDGE_PROMPT
        prompt = prompt.replace('{question}', str(line['question_en'] if 'question_en' in line else line['question']))
        prompt = prompt.replace('{options}', _format_options(_option_items_from_line(line)))
        prompt = prompt.replace('{ground_truth_analysis}', str(line['explanation_en']))
        prompt = prompt.replace('{model_answer}', str(prediction))
        return prompt

    def _apply_official_judge_reasoning_effort(self, eval_file, judge_kwargs):
        if 'reasoning_effort' not in judge_kwargs:
            infer_model_name = _infer_model_name_from_eval_file(eval_file, self.dataset_name)
            reasoning_effort = _official_reasoning_effort_from_infer_model(infer_model_name)
            if reasoning_effort is not None:
                judge_kwargs['reasoning_effort'] = reasoning_effort
        return judge_kwargs

    def evaluate(self, eval_file, **judge_kwargs):
        judge_kwargs = self._apply_official_judge_reasoning_effort(eval_file, judge_kwargs)
        judge_model_name = judge_kwargs.get('model', self.DEFAULT_JUDGE_MODEL)
        self._validate_judge_model_name(judge_model_name)
        acc = self.evaluate_accuracy(eval_file)
        rpf = self.evaluate_cot(eval_file, **judge_kwargs)
        result = pd.concat([acc, rpf], ignore_index=True)
        score_file = get_intermediate_file_path(eval_file, f'_{judge_model_name}_cot_acc', 'csv')
        dump(result, score_file)
        return result

    def evaluate_accuracy(self, eval_file):
        data = load(eval_file).copy()
        data = data.sort_values(by='index')
        data['prediction'] = [str(x) for x in data['prediction']]

        parsed_answers, scores, statuses, errors = [], [], [], []
        meta = {str(row['index']): row for _, row in self.data.iterrows()}
        for _, row in data.iterrows():
            try:
                parsed = _parse_boxed_answer(row['prediction'])
                meta_row = meta[str(row['index'])]
                score = _score_answer(parsed, meta_row['answer_en'], meta_row['question_type'])
                status, error = True, ''
            except Exception as err:
                parsed = ''
                score = 0
                status = False
                error = str(err)
            parsed_answers.append(parsed)
            scores.append(score)
            statuses.append(status)
            errors.append(error)

        data['llm_answer'] = parsed_answers
        data['score'] = scores
        data['status'] = statuses
        data['error'] = errors
        detail_file = get_intermediate_file_path(eval_file, '_superchem_result')
        dump(data, detail_file)

        acc = self._summarize_accuracy(data)
        score_file = get_intermediate_file_path(eval_file, '_acc', 'csv')
        dump(acc, score_file)
        return acc

    def evaluate_cot(self, eval_file, **judge_kwargs):
        judge_kwargs = self._apply_official_judge_reasoning_effort(eval_file, judge_kwargs)
        judge_model_name = judge_kwargs.pop('model', self.DEFAULT_JUDGE_MODEL)
        self._validate_judge_model_name(judge_model_name)

        nproc = judge_kwargs.pop('nproc', 4)
        judge_kwargs.setdefault('temperature', 1.0)
        judge_kwargs.setdefault('max_tokens', 16384)
        judge_kwargs.setdefault('stream', True)
        data = load(eval_file).copy()
        meta = {str(row['index']): row for _, row in self.data.iterrows()}
        data['judge_prompt'] = [
            self.build_judge_prompt(meta[str(row['index'])], row['prediction'])
            for _, row in data.iterrows()
        ]

        storage = get_intermediate_file_path(eval_file, f'_{judge_model_name}_cot_judge')
        tmp_file = get_intermediate_file_path(eval_file, f'_{judge_model_name}_cot_judge_tmp', 'pkl')
        if not osp.exists(storage):
            model = build_judge(model=judge_model_name, **judge_kwargs)
            assert model.working(), 'SUPERChem RPF evaluation requires a working official judge API\n' + DEBUG_MESSAGE

            ans = load(tmp_file) if osp.exists(tmp_file) else {}
            lines = [data.iloc[i] for i in range(len(data))]
            indices = [line['index'] for line in lines]
            tups = [(model, line) for line in lines if line['index'] not in ans]
            keys = [idx for idx in indices if idx not in ans]
            if keys:
                track_progress_rich(
                    superchem_auxeval,
                    tups,
                    nproc=nproc,
                    chunksize=nproc,
                    keys=keys,
                    save=tmp_file,
                )
                ans = load(tmp_file)

            judged = data.copy()
            judged['matched_checkpoints'] = [ans[idx]['matched_checkpoints'] for idx in indices]
            judged['total_checkpoints'] = [ans[idx]['total_checkpoints'] for idx in indices]
            judged['evaluation_details'] = [ans[idx]['evaluation_details'] for idx in indices]
            judged['judge_output'] = [ans[idx]['judge_output'] for idx in indices]
            dump(judged, storage)
        judged = load(storage)
        judged = self._add_official_weighted_rpf(judged, meta)
        dump(judged, storage)

        rpf = self._summarize_rpf(judged)
        score_file = get_intermediate_file_path(eval_file, f'_{judge_model_name}_cot_rpf', 'csv')
        dump(rpf, score_file)
        return rpf

    def _validate_judge_model_name(self, judge_model_name):
        if judge_model_name != self.DEFAULT_JUDGE_MODEL:
            raise ValueError(
                f'SUPERChem official CoT judge is {self.DEFAULT_JUDGE_MODEL}; got {judge_model_name}. '
                'Use evaluate_accuracy directly for judge-free pass@1, or use the official judge model for RPF.'
            )

    @staticmethod
    def _summarize_accuracy(data):
        result = defaultdict(list)
        result['split'].append('none')
        result['Overall'].append(float(np.mean(data['score'])) if len(data) else 0.0)
        if 'field' in data:
            for field in _nonempty_unique_values(data['field']):
                sub = data[data['field'] == field]
                result[field].append(float(np.mean(sub['score'])) if len(sub) else 0.0)
        if 'difficulty' in data:
            for difficulty in _nonempty_unique_values(data['difficulty']):
                sub = data[data['difficulty'] == difficulty]
                result[f'difficulty_{difficulty}'].append(float(np.mean(sub['score'])) if len(sub) else 0.0)
        result['metric'].append('pass@1')
        return pd.DataFrame(result)

    @staticmethod
    def _add_official_weighted_rpf(data, meta):
        data = data.copy()
        scores = []
        for _, row in data.iterrows():
            meta_row = meta.get(str(row['index']), {})
            explanation = meta_row.get('explanation_en', row.get('explanation_en', ''))
            scores.append(
                _official_weighted_rpf(
                    explanation,
                    row.get('evaluation_details', []),
                    row.get('matched_checkpoints', 0),
                    row.get('total_checkpoints', 0),
                )
            )
        data['rpf'] = scores
        return data

    @staticmethod
    def _summarize_rpf(data):
        if 'official_split' in data:
            official_data = data[data['official_split'].isin(['release', 'holdout'])]
            if len(official_data):
                data = official_data
        result = defaultdict(list)
        result['split'].append('none')
        result['Overall'].append(_mean_or_zero(data['rpf']) if len(data) else 0.0)
        if 'field' in data:
            for field in _nonempty_unique_values(data['field']):
                sub = data[data['field'] == field]
                result[field].append(_mean_or_zero(sub['rpf']) if len(sub) else 0.0)
        if 'difficulty' in data:
            for difficulty in _nonempty_unique_values(data['difficulty']):
                sub = data[data['difficulty'] == difficulty]
                result[f'difficulty_{difficulty}'].append(_mean_or_zero(sub['rpf']) if len(sub) else 0.0)
        result['metric'].append('RPF-CoT')
        return pd.DataFrame(result)

    @classmethod
    def report_primary_metric(cls, metrics):
        if not isinstance(metrics, dict) or not metrics:
            return {}
        if 'Overall' in metrics:
            return {'Overall Acc': metrics['Overall'] * 100}
        return super().report_primary_metric(metrics)
