MULTIMODAL_TAG_PATTERN = re.compile(r'<MultiModal>(.*?)</MultiModal>', flags=re.IGNORECASE | re.DOTALL)
MARKDOWN_IMAGE_PATTERN = re.compile(r'!?\s*\[(.+)\]\s*\(([^)]+)\)', flags=re.MULTILINE | re.DOTALL)
BOXED_ANSWER_PATTERN = re.compile(r'\\boxed\{(.+?)\}', flags=re.DOTALL)
CHECKPOINT_WEIGHT_PATTERN = re.compile(
    r'<Checkpoint>\[.*?\]\s*\((\d+(?:\.\d+)?)\)\s*</Checkpoint>',
    flags=re.DOTALL,
)
